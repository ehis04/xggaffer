def _build_reverse_index(source):
    index = {}
    for canonical, names in CANONICAL_TEAM_NAMES.items():
        if source in names:
            index[names[source]] = canonical
    if source == "understat":
        for alias, canonical in UNDERSTAT_ALIASES.items():
            index[alias] = canonical
    return index


_reverse_cache = {}


def to_canonical(source_name, source):
    if source not in _reverse_cache:
        _reverse_cache[source] = _build_reverse_index(source)

    index = _reverse_cache[source]
    if source_name in index:
        return index[source_name]

    if source_name in CANONICAL_TEAM_NAMES:
        return source_name

    raise KeyError(
        f"Unknown team '{source_name}' for source '{source}'."
    )


def from_canonical(canonical_name, source):
    if canonical_name not in CANONICAL_TEAM_NAMES:
        raise KeyError(
            f"Unknown canonical team '{canonical_name}'."
        )

    names = CANONICAL_TEAM_NAMES[canonical_name]
    if source not in names:
        raise KeyError(
            f"Source '{source}' not mapped for team '{canonical_name}'."
        )
    return names[source]